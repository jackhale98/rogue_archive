/**
 * Writes the symbol tables of the graphical build's libraries (a C file
 * linked with port/libraries.c) from FPC Valkyrie's own library loaders:
 *
 * - SDL 3 and SDL3_image: every name `libs/vsdl3library.pas` and
 *   `libs/vsdl3imagelibrary.pas` load (`GetSymbol('...')`), as the address of
 *   the function the module is linked with (Emscripten's SDL 3 port, our
 *   SDL3_image build). A name the library does not export (its own `.sym`
 *   list) is an error: the loader would stop on it.
 * - GL: for each function `libs/vgl*vars.inc` declares, a stand-in with the
 *   same WebAssembly signature, used only when WebGL 2 has no such function
 *   (desktop GL's glPolygonMode, glTexImage1D...): it reports the name once
 *   and does nothing. A call through a pointer with another signature would
 *   trap, so the signature is the Pascal declaration's.
 *
 *   node libraries.mjs <fpcvalkyrie> <SDL source> <SDL_image source> <output.c>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [valkyrie, sdl, sdlImage, output] = process.argv.slice(2);
if (!output) {
  console.error('usage: libraries.mjs <fpcvalkyrie> <SDL source> <SDL_image source> <output.c>');
  process.exit(2);
}

const read = (path) => readFileSync(path, 'utf8');
const loaded = (unit) => [
  ...new Set(
    [...read(join(valkyrie, 'libs', unit)).matchAll(/GetSymbol\(\s*'(\w+)'\s*\)/g)].map((m) => m[1]),
  ),
];
const exported = (path) => new Set([...read(path).matchAll(/^\s+(\w+);/gm)].map((m) => m[1]));

function table(name, symbols, exports, library) {
  const missing = symbols.filter((s) => !exports.has(s));
  if (missing.length) {
    console.error(`error: ${library} does not export ${missing.join(', ')}`);
    process.exit(1);
  }
  return [
    `const ra_symbol ${name}[] = {`,
    ...symbols.map((s) => `  {"${s}", (void *)${s}},`),
    '  {NULL, NULL},',
    '};',
  ];
}

const sdlSymbols = loaded('vsdl3library.pas');
const imageSymbols = loaded('vsdl3imagelibrary.pas');
if (sdlSymbols.length < 100 || imageSymbols.length < 5) {
  console.error('error: found too few names in the SDL loaders');
  process.exit(1);
}

// Pascal type -> C type of the same WebAssembly value type.
function cType(type) {
  if (/^(GLfloat|GLclampf|Single)$/.test(type)) return 'float';
  if (/^(GLdouble|GLclampd|Double)$/.test(type)) return 'double';
  if (/^(GLint64|GLuint64|Int64|QWord)$/.test(type)) return 'int64_t';
  return 'int32_t'; // integers, booleans, enums and every pointer
}

const gl = [];
for (const unit of ['vgl15vars.inc', 'vgl21vars.inc', 'vgl33vars.inc']) {
  const pattern = /^\s*(\w+)\s*:\s*(procedure|function)\s*(?:\(([^)]*)\))?\s*(?::\s*(\w+))?\s*;\s*extdecl;/gm;
  for (const m of read(join(valkyrie, 'libs', unit)).matchAll(pattern)) {
    const [, name, kind, params = '', result] = m;
    const types = [];
    for (const group of params.split(';').filter((g) => g.trim())) {
      const [names, type] = group.split(':').map((s) => s.trim());
      const count = names.replace(/^(const|var|out)\s+/, '').split(',').length;
      for (let i = 0; i < count; i++) types.push(cType(type));
    }
    gl.push({ name, result: kind === 'function' ? cType(result) : 'void', types });
  }
}
if (gl.length < 300) {
  console.error(`error: found only ${gl.length} GL declarations`);
  process.exit(1);
}

const lines = [
  "/* Generated by games/drl/scripts/libraries.mjs from FPC Valkyrie's library loaders. */",
  '#include <stddef.h>',
  '#include <stdint.h>',
  '#include <SDL3/SDL.h>',
  '#include <SDL3_image/SDL_image.h>',
  '',
  'typedef struct { const char *name; void *address; } ra_symbol;',
  'void ra_gl_absent(const char *name);',
  '',
  ...table('ra_sdl3_symbols', sdlSymbols, exported(join(sdl, 'src/dynapi/SDL_dynapi.sym')), 'SDL 3'),
  '',
  ...table(
    'ra_sdl3_image_symbols',
    imageSymbols,
    exported(join(sdlImage, 'src/SDL_image.sym')),
    'SDL3_image',
  ),
  '',
];
for (const f of gl) {
  const params = f.types.length ? f.types.map((t, i) => `${t} a${i}`).join(', ') : 'void';
  const body = f.result === 'void' ? '' : ' return 0;';
  lines.push(`static ${f.result} absent_${f.name}(${params}) { ra_gl_absent("${f.name}");${body} }`);
}
lines.push('', 'const ra_symbol ra_gl_absent_symbols[] = {');
for (const f of gl) lines.push(`  {"${f.name}", (void *)absent_${f.name}},`);
lines.push('  {NULL, NULL},', '};', '');
writeFileSync(output, lines.join('\n'));
console.log(
  `libraries: ${sdlSymbols.length} SDL 3, ${imageSymbols.length} SDL3_image, ${gl.length} GL declarations`,
);
